export const getModelById = (id: string): StudioModel | undefined => {
  const normalizedId = id.trim();
  const model = [...IMAGE_MODELS, ...VIDEO_MODELS, ...LIPSYNC_MODELS, ...AUDIO_MODELS, ...TEXT_MODELS].find((entry) => entry.id === normalizedId);
  if (model) {
    return model;
  }
  return undefined;
};

export const getModelsByType = (type: StudioModelMediaType): StudioModel[] => {
  switch (type) {
    case 'image':
      return IMAGE_MODELS;
    case 'video':
      return [...VIDEO_MODELS, ...LIPSYNC_MODELS];
    case 'audio':
      return AUDIO_MODELS;
    case 'text':
      return TEXT_MODELS;
    default:
      return [];
  }
};

export const getModelsByTypeAndGroup = (
  type: StudioModelMediaType,
  uiGroup: StudioModelUiGroup
): StudioModel[] => getModelsByType(type).filter((model) => model.uiGroup === uiGroup);

