const mergeCatalogModels = (primary: StudioModel[], secondary: StudioModel[]): StudioModel[] => {
  const seen = new Set(primary.map((model) => model.id));
  const merged = [...primary];
  for (const model of secondary) {
    if (seen.has(model.id)) {
      continue;
    }
    seen.add(model.id);
    merged.push(model);
  }
  return merged;
};

